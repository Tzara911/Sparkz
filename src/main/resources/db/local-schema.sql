-- Include the supplied profile columns for #24/#25; omit the auth.users FK locally.
create table profiles (
    user_id uuid primary key,
    username text unique,
    email text,
    first_name text,
    last_name text,
    school_name text,
    grade_year text,
    address text,
    phone text,
    dob date,
    created_at timestamp with time zone default current_timestamp,
    time_zone text,
    account_status text not null default 'active' check (account_status in ('active', 'deactivated')),
    bio text,
    avatar_url text,
    onboarding_completed boolean not null default false,
    updated_at timestamp with time zone not null default current_timestamp
);
create table skills (
    skill_id bigint generated by default as identity primary key,
    skill_name text not null check (length(trim(skill_name)) > 0),
    description text
);
create table user_skills (
    user_id uuid not null references profiles(user_id) on delete cascade,
    skill_id bigint not null references skills(skill_id),
    skill_type text not null check (skill_type in ('teach', 'learn')),
    primary key(user_id, skill_id, skill_type)
);
create table match_requests (
    request_id bigint generated always as identity primary key,
    sender_id uuid not null references profiles(user_id) on delete cascade,
    receiver_id uuid not null references profiles(user_id) on delete cascade,
    skill_id bigint not null references skills(skill_id),
    status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'canceled')),
    created_at timestamp with time zone not null default current_timestamp,
    status_updated_at timestamp with time zone not null default current_timestamp,
    check (sender_id <> receiver_id)
);
create index match_requests_incoming on match_requests(receiver_id, created_at);
create index match_requests_outgoing on match_requests(sender_id, created_at);
create table blocked_users (
    blocker_id uuid not null references profiles(user_id) on delete cascade,
    blocked_id uuid not null references profiles(user_id) on delete cascade,
    created_at timestamp with time zone not null default current_timestamp,
    primary key(blocker_id, blocked_id),
    check (blocker_id <> blocked_id)
);

-- Availability uses the same user/day composite parent key as Supabase.
create table profile_available_days (
    user_id uuid not null references profiles(user_id),
    day_of_week smallint not null check (day_of_week between 1 and 7),
    primary key(user_id, day_of_week)
);
create table profile_available_slots (
    slot_id bigint generated always as identity primary key,
    user_id uuid not null,
    day_of_week smallint not null,
    start_time time not null,
    end_time time not null,
    foreign key(user_id, day_of_week) references profile_available_days(user_id, day_of_week),
    check (start_time < end_time)
);
