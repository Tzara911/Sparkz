-- LOCAL/TEST CONTRACT ONLY. Not a migration for an existing Supabase database.
create table profiles (
    user_id uuid primary key,
    account_status varchar(20) not null,
    onboarding_completed boolean not null default false,
    school_name varchar(200)
);
create table skills (skill_id bigint primary key, skill_name varchar(100) not null);
create table user_skills (
    user_id uuid not null references profiles(user_id),
    skill_id bigint not null references skills(skill_id),
    skill_type varchar(20) not null check (skill_type in ('Teaching', 'Learning')),
    primary key(user_id, skill_id, skill_type)
);
create table match_requests (
    request_id bigint generated by default as identity primary key,
    sender_id uuid not null references profiles(user_id),
    receiver_id uuid not null references profiles(user_id),
    skill_id bigint not null references skills(skill_id),
    status varchar(20) not null check (status in ('Pending', 'Accepted', 'Declined', 'Canceled')),
    created_at timestamp with time zone not null,
    status_updated_at timestamp with time zone not null,
    check (sender_id <> receiver_id)
);
create index match_requests_incoming on match_requests(receiver_id, created_at);
create index match_requests_outgoing on match_requests(sender_id, created_at);
create table blocked_users (
    blocker_id uuid not null references profiles(user_id),
    blocked_id uuid not null references profiles(user_id),
    created_at timestamp with time zone default current_timestamp,
    primary key(blocker_id, blocked_id)
);
